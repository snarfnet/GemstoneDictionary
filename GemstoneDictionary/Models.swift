struct ScanMetrics {
    var hue: Double
    var saturation: Double
    var brightness: Double
    var clarityScore: Int
    var levelScore: Int
    var coverageScore: Int
    var estimatedMillimeters: Int?
    var stoneLikelihood: Int = 50

    var isLikelyStone: Bool { stoneLikelihood >= 50 }

    var stoneLikelihoodLabel: String {
        switch stoneLikelihood {
        case 70...100: return isEnglish() ? "Likely a gemstone" : "天然石の可能性が高い"
        case 50..<70: return isEnglish() ? "Possibly a gemstone" : "天然石かもしれません"
        case 35..<50: return isEnglish() ? "Low confidence" : "判定の確信度が低い"
        default: return isEnglish() ? "Unlikely a gemstone" : "天然石ではない可能性があります"
        }
    }

    private func isEnglish() -> Bool {
        Locale.preferredLanguages.first?.hasPrefix("en") == true
    }

    var clarityLabel: String {
        switch clarityScore {
        case 82...100: return "透明感が高い"
        case 60..<82: return "半透明"
        case 38..<60: return "やや不透明"
        default: return "不透明に近い"
        }
    }

    var levelLabel: String {
        switch levelScore {
        case 86...100: return "S"
        case 70..<86: return "A"
        case 52..<70: return "B"
        default: return "C"
        }
    }

    var sizeLabel: String {
        estimatedMillimeters.map { "約\($0)mm目安" } ?? "見かけサイズ \(coverageScore)%"
    }

    var sizeNote: String {
        estimatedMillimeters == nil
            ? "基準物なし。実寸ではなく、画面内で石が占める大きさです。"
            : "基準物からの推定です。石と基準物を同じ高さで写すほど近い値になります。"
    }

    var sizeConfidenceLabel: String {
        switch coverageScore {
        case 42...100: return "高め"
        case 24..<42: return "中くらい"
        default: return "低め"
        }
    }

    var sizeConfidenceNote: String {
        if estimatedMillimeters == nil {
            return "基準物なしのため、実寸ではなく画面内の見かけサイズです。"
        }
        if coverageScore >= 42 {
            return "石が十分大きく写っています。基準物と同じ高さなら推定値が安定しやすい状態です。"
        }
        if coverageScore >= 24 {
            return "使える目安です。石と基準物をもう少し大きく、同じ高さで写すと安定します。"
        }
        return "石が小さく写っています。画面中央に大きく入れ、基準物を横に置いて撮り直してください。"
    }

    var captureQualityWarnings: [String] {
        var warnings: [String] = []
        if brightness < 24 {
            warnings.append("暗めです。白い紙の上で、影を避けて撮ると色が出やすくなります。")
        }
        if brightness > 88 {
            warnings.append("明るすぎます。反射を避け、少し角度を変えて撮ってください。")
        }
        if saturation < 14 {
            warnings.append("色が弱く出ています。背景の色かぶりを避け、自然光に近い明かりで撮ってください。")
        }
        if coverageScore < 24 {
            warnings.append("石が小さく写っています。画面の中央に大きく入れてください。")
        }
        return warnings.isEmpty ? ["撮影状態は良好です。同じ条件で数秒止めると候補が安定しやすくなります。"] : warnings
    }
}

struct StoneCandidate: Identifiable {
    let gemstone: Gemstone
    let score: Int

    var id: String { gemstone.id }
}

extension Gemstone {
    var shortTransparency: String {
        if transparency.contains("透明〜半透明") { return "透明〜半透明" }
        if transparency.contains("透明") { return "透明" }
        if transparency.contains("半透明") { return "半透明" }
        if transparency.contains("不透明") { return "不透明" }
        return transparency
    }

    var hueCenter: Double {
        if hueRange.lowerBound == 0, hueRange.upperBound == 360 {
            return 180
        }
        if hueRange.lowerBound >= 300 {
            return ((hueRange.lowerBound + hueRange.upperBound + 360) / 2).truncatingRemainder(dividingBy: 360)
        }
        return (hueRange.lowerBound + hueRange.upperBound) / 2
    }

    var saturationCenter: Double {
        (saturationRange.lowerBound + saturationRange.upperBound) / 2
    }
}

